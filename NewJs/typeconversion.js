let a = "5";
let b = 10;

let sum = Number(a) + b;
console.log("Sum of a and b is ", sum);
//Sum of a and b is  15

console.log("implicit type conversion of a and b is ", a + b);
//implicit type conversion of a and b is  510

console.log("implicit type conversion of a and b is ", a - b);
//implicit type conversion of a and b is  -5